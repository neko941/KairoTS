"""Two-sample discrimination by leave-one-out 1-nearest-neighbour accuracy over the
pooled real and generated windows (flattened, Euclidean): each window is labelled
real or generated by its nearest other window. The score is `|accuracy - 0.5|`, the
form of TimeGAN's discriminative score: 0 when the samples cannot be told from real
windows, 0.5 when they can always be told apart, or when every sample is an exact
copy of a real window (accuracy 0). Merging keeps the windows.
"""

from dataclasses import dataclass, field

import torch
from torch import Tensor


@dataclass(kw_only=True)
class DiscriminativeScore:
    ROLES = ("metric",)
    TASKS = ("Generation",)
    NEEDS = ("samples", "target")
    PHASES = ("test",)
    DIRECTION = "min"

    real: list[Tensor] = field(default_factory=list)
    generated: list[Tensor] = field(default_factory=list)

    @dataclass(kw_only=True)
    class Config:
        name: str = "DiscriminativeScore"

    def __init__(self, *, config: Config | None = None) -> None:
        self.real = []
        self.generated = []

    def update(self, *, prediction: Tensor, target: Tensor) -> None:
        self.generated.append(prediction.flatten(1).double())
        self.real.append(target.flatten(1).double())

    def merge(self, *, other: DiscriminativeScore) -> None:
        self.real += other.real
        self.generated += other.generated

    def compute(self) -> float:
        if not self.real or not self.generated:
            raise ValueError("DiscriminativeScore has no observations")
        real, generated = torch.cat(self.real), torch.cat(self.generated)
        windows = torch.cat([real, generated])
        labels = torch.cat(
            [
                torch.zeros(len(real), dtype=torch.bool),
                torch.ones(len(generated), dtype=torch.bool),
            ]
        )
        distances = torch.cdist(windows, windows).fill_diagonal_(torch.inf)
        accuracy = (labels[distances.argmin(dim=1)] == labels).double().mean()
        return float((accuracy - 0.5).abs())
